const { chromium, expect } = require('playwright/test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const root = path.resolve(__dirname, '..')
const credentials = Object.fromEntries(fs.readFileSync(path.join(root, 'backend/.env.local'), 'utf8').split(/\r?\n/).filter(x=>x.includes('=')).map(x=>{const i=x.indexOf('=');return [x.slice(0,i),x.slice(i+1).replace(/^['"]|['"]$/g,'')]}))
const output = path.join(root, 'screenshots')
fs.mkdirSync(output,{recursive:true})
const failures=[]
async function capture(page,name) {
  await page.evaluate(async()=>{await document.fonts.ready;await Promise.all([...document.images].map(img=>img.decode().catch(()=>{})))})
  assert.equal(await page.evaluate(()=>[...document.images].filter(i=>!i.naturalWidth).length),0,'broken image')
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,'horizontal overflow')
  await page.evaluate(()=>new Promise(resolve=>{window.scrollTo(0,0);requestAnimationFrame(()=>requestAnimationFrame(resolve))}))
  await page.screenshot({path:path.join(output,name+'.png'),fullPage:!name.includes('移动端')})
}
(async()=>{
  const browser=await chromium.launch({headless:true,...(process.env.CHROME_BIN?{executablePath:process.env.CHROME_BIN}:{})})
  const desktop=await browser.newContext({viewport:{width:1440,height:1024},locale:'zh-CN'})
  const mobile=await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:1,isMobile:true,hasTouch:true,locale:'zh-CN'})
  const admin=await desktop.newPage(), web=await desktop.newPage(), phone=await mobile.newPage()
  for(const page of [admin,web,phone]) page.on('pageerror',e=>failures.push(e.message))
  let createdId
  try {
    await admin.goto('http://127.0.0.1:5174/')
    await expect(admin.getByRole('heading',{name:'登录策展工作台'})).toBeVisible()
    await capture(admin,'01-管理后台-登录')
    await admin.getByLabel('管理员账号').fill(credentials.ADMIN_USERNAME)
    await admin.getByLabel('密码',{exact:true}).fill(credentials.ADMIN_PASSWORD)
    await admin.getByRole('button',{name:'登录工作台'}).click()
    await expect(admin.locator('tbody tr')).toHaveCount(5)
    await capture(admin,'02-管理后台-展览管理')
    await admin.locator('tr').filter({hasText:'厦园有光'}).getByRole('button',{name:'编辑',exact:true}).click()
    await expect(admin.getByLabel('展览标题')).toHaveValue('厦园有光')
    await capture(admin,'03-管理后台-编辑展览')
    await admin.getByRole('button',{name:'取消编辑'}).click()
    await web.goto('http://127.0.0.1:5173/')
    await expect(web.locator('.exhibition-card')).toHaveCount(3)
    await expect(web.locator('.work-card')).toHaveCount(4)
    await capture(web,'04-Web-展览首页')
    await web.getByLabel('搜索展览名称').fill('不存在的展览')
    await web.getByRole('button',{name:'搜索',exact:true}).click()
    await expect(web.getByText('没有符合条件的公开展览')).toBeVisible()
    await web.getByRole('button',{name:'重置'}).click()
    await expect(web.locator('.exhibition-card')).toHaveCount(3)
    await web.locator('.exhibition-card').filter({hasText:'厦园有光'}).click()
    await expect(web.locator('.detail-hero h1')).toHaveText('厦园有光')
    await capture(web,'05-Web-展览详情')
    await web.reload()
    await expect(web.locator('.detail-hero h1')).toHaveText('厦园有光')
    await phone.goto('http://127.0.0.1:5175/')
    await expect(phone.locator('.card')).toHaveCount(3)
    await capture(phone,'06-移动端-发现展览')
    await phone.getByRole('button',{name:'展出中',exact:true}).click()
    await expect(phone.locator('.card')).toHaveCount(1)
    await phone.locator('.card').click()
    await expect(phone.locator('.detail h1')).toHaveText('厦园有光')
    await capture(phone,'07-移动端-展览详情')
    await phone.reload()
    await expect(phone.locator('.detail h1')).toHaveText('厦园有光')
    // UI 创建 -> 数据库持久化 -> 两个观众端可见 -> 下架隔离 -> 删除本测试草稿。
    const title='三端联调测试-'+Date.now()
    await admin.getByRole('button',{name:'创建展览'}).click()
    await admin.getByLabel('展览标题').fill(title)
    await admin.getByLabel('展览简介').fill('从管理后台创建，用于核验三端共享数据库。')
    await admin.getByLabel('策展序言').fill('自动化测试创建的临时记录，验证结束后删除。')
    await admin.getByLabel('结束时间').fill('2026-10-01T09:00')
    await admin.getByRole('button',{name:'保存展览'}).click()
    await expect(admin.getByRole('alert')).toContainText('结束时间必须晚于开始时间')
    await admin.getByLabel('结束时间').fill('2026-11-30T18:00')
    await admin.getByLabel('业务状态',{exact:true}).selectOption('on_view')
    await admin.getByLabel('向观众公开').check()
    const saved=admin.waitForResponse(r=>r.url().endsWith('/api/admin/exhibitions') && r.request().method()==='POST' && r.status()===201)
    await admin.getByRole('button',{name:'保存展览'}).click()
    createdId=(await (await saved).json()).id
    await admin.reload()
    await expect(admin.locator('tbody tr').filter({hasText:title})).toBeVisible()
    await web.goto('http://127.0.0.1:5173/#exhibition/'+createdId)
    await expect(web.locator('.detail-hero h1')).toHaveText(title)
    await phone.goto('http://127.0.0.1:5175/#exhibition/'+createdId)
    await expect(phone.locator('.detail h1')).toHaveText(title)
    admin.once('dialog',d=>d.accept())
    await admin.locator('tr').filter({hasText:title}).getByRole('button',{name:'下架'}).click()
    await expect(admin.locator('tr').filter({hasText:title})).toContainText('未公开')
    await web.reload(); await phone.reload()
    await expect(web.getByRole('alert')).toContainText('展览不存在或尚未公开')
    await expect(phone.getByRole('alert')).toContainText('展览不存在或尚未公开')
    await admin.locator('tr').filter({hasText:title}).getByRole('button',{name:'编辑',exact:true}).click()
    await admin.getByLabel('业务状态',{exact:true}).selectOption('draft')
    await admin.getByRole('button',{name:'保存展览'}).click()
    await expect(admin.locator('tr').filter({hasText:title}).getByRole('button',{name:'删除'})).toBeVisible()
    admin.once('dialog',d=>d.accept())
    await admin.locator('tr').filter({hasText:title}).getByRole('button',{name:'删除'}).click()
    await expect(admin.locator('tbody tr')).toHaveCount(5)
    createdId=null
    await phone.goto('http://127.0.0.1:5175/')
    await expect(phone.locator('.card')).toHaveCount(3)
    await phone.route('**/api/exhibitions*',route=>route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({message:'数据库暂时不可用，请稍后重试'})}))
    await phone.getByRole('button',{name:'刷新'}).click()
    await expect(phone.getByRole('alert')).toContainText('数据库暂时不可用')
    await phone.unroute('**/api/exhibitions*')
    await phone.getByRole('button',{name:'重新加载'}).click()
    await expect(phone.locator('.card')).toHaveCount(3)
    await admin.getByRole('button',{name:'退出',exact:true}).click()
    await expect(admin.getByRole('heading',{name:'登录策展工作台'})).toBeVisible()
    assert.deepEqual(failures,[],'browser runtime errors')
    fs.writeFileSync(path.join(root,'tests/browser-result.json'),JSON.stringify({passed:true,viewports:['1440x1024','390x844'],screenshots:7,checks:['admin login/logout','CRUD through browser UI','date validation','database persistence after reload','Web/mobile publication and hiding','search empty state','mobile status filter','detail deep-link reload','simulated 503 and retry','images and horizontal overflow','no pageerror'],browser:browser.version()},null,2))
    console.log('PASS: three-client browser workflow; 7 screenshots saved.')
  } finally {
    if(createdId) console.error('Test interrupted; temporary exhibition ID:',createdId)
    await browser.close()
  }
})().catch(e=>{console.error(e);process.exitCode=1})
